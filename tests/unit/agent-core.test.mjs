const replyStyle = await readFile(new URL('persona/reply-style.md', root), 'utf8')

function harness(initial = ['unsafe_shell']) {
  const globals = new Set(initial), masks = new Set(), listeners = new Set(), effects = []
  const history = []
  const emit = () => { for (const fn of [...listeners]) fn() }
  const ctx = {
    tools: {
      definitions: () => [...globals].map(name => ({ name })),
      restrict({ allow }) {
        assert([...allow].every(name => globals.has(name)))
        masks.add(allow)
        history.push([...masks].map(x => [...x]))
        emit()
        return () => { masks.delete(allow); history.push([...masks].map(x => [...x])); emit() }
      },
    },
    effect: fn => effects.push(fn()),
    on: (event, fn) => { assert.equal(event, 'tools/change'); listeners.add(fn); return () => listeners.delete(fn) },
  }
  return {
    ctx, masks, listeners, history,
    add: name => { globals.add(name); emit() },
    remove: name => { globals.delete(name); emit() },
    visible: () => [...globals].filter(name => [...masks].every(mask => mask.has(name))),
    dispose: () => { for (const off of effects.reverse()) off() },
  }
}

test('agent-core: 名称校验拒绝提示模板、换行、过长和未知配置，不回显输入', () => {
  assert.deepEqual(validateAgentConfig({ AGENT_DISPLAY_NAME: '  澄梦 · CM  ' }), { AGENT_DISPLAY_NAME: '澄梦 · CM' })
  for (const value of [null, [], {}, { AGENT_DISPLAY_NAME: 'x', apiKey: 'secret' },
    ...['', ' ', '{{model}}', 'x\ny', 'x'.repeat(25), '<script>', 'x\u202ey'].map(AGENT_DISPLAY_NAME => ({ AGENT_DISPLAY_NAME }))]) {
    assert.throws(() => validateAgentConfig(value), /^Error: AGENT_(CONFIG|DISPLAY_NAME)_INVALID$/)
  }
})

test('agent-core: 完整长 Persona 被保留，替换显示名，无未解析变量', () => {
  const text = renderPersona(template, { AGENT_DISPLAY_NAME: '澄梦' })
  assert(text.length > 8192, 'Detailed Persona must not be subject to the Skill tool-result limit')
    assert(text.startsWith('# 先使用记忆库与基础工具'))
  assert(text.includes('你是 澄梦'))
  assert(text.endsWith('不要把对话变成展示规则的仪式。'))
  assert(!text.includes('[[AGENT_DISPLAY_NAME]]'))
  assert.throws(() => renderPersona('x {{missing}} [[AGENT_DISPLAY_NAME]]', config), /PERSONA_TEMPLATE_INVALID/)
})

test('agent-core: 原生预设含精简文件、平台命令和网页工具，不启用无关自动化', () => {
  const patch = createPatch(config, template, replyStyle)
  assert.equal(patch.length, 1)
  assert.deepEqual(Object.keys(patch[0]), ['insert'])
  const row = patch[0].insert.find(row => row.id === 'preset-chengmeng')
  assert.equal(row.name, '@deepseek-ai/dsh-agent-preset')
  assert.equal(row.config.id, 'chengmeng')
  assert.equal(row.config.name, config.AGENT_DISPLAY_NAME)
  const persona = row.config.plugins.find(row => row.name === '@deepseek-ai/dsh-persona')
  assert.equal(persona.config.complete, false)
  assert.equal(persona.config.prefix, renderPersona(template, config))
  assert.equal(persona.config.suffix, renderPersona(replyStyle, config))
  const serialized = JSON.stringify(patch)
  assert(!/dsh-tool-(schedule|subagent)|dsh-agent-instructions|memsearch-dsh/.test(serialized))
  for(const name of ['dsh-tool-fs','dsh-tool-fs-search','dsh-tool-web',process.platform==='win32'?'dsh-tool-pwsh':'dsh-tool-bash']) assert(serialized.includes(name))
})

