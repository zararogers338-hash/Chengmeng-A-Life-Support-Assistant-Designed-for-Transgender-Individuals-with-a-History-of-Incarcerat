test('agent-core: 缺少记忆插件时拒绝所有继承的全局工具', () => {
  const h = harness(['unsafe_shell', 'upload', 'browser'])
  h.ctx.effect(() => installToolPolicy(h.ctx))
  assert.deepEqual(h.visible(), [])
  h.add('new_external_tool')
  assert.deepEqual(h.visible(), [])
  h.dispose()
  assert.equal(h.masks.size, 0)
  assert.equal(h.listeners.size, 0)
})

test('agent-core: 晚加载、卸载、重装记忆工具时刷新白名单，替换时无权限空窗', () => {
  const h = harness()
  h.ctx.effect(() => installToolPolicy(h.ctx))
  for (const tool of ['memory_status', 'propose_memory', 'recall_memory']) h.add(tool)
  assert.deepEqual(h.visible(), ['memory_status', 'propose_memory', 'recall_memory'])
  h.remove('recall_memory')
  assert.deepEqual(h.visible(), ['memory_status', 'propose_memory'])
  h.add('recall_memory')
  assert.equal(h.masks.size, 1)
  assert(h.history.every(masks => masks.length > 0))
  assert.equal(h.listeners.size, 1)
  h.dispose()
})

test('agent-core: 配置错误先失败，宿主限制注册失败不能假装成功', () => {
  const h = harness()
  for (const config of [null, [], { allowShell: true }]) assert.throws(() => apply(h.ctx, config), /AGENT_CORE_CONFIG_INVALID/)
  assert.equal(h.masks.size, 0)
  h.ctx.tools.restrict = () => { throw new Error('scoped context required') }
  assert.throws(() => installToolPolicy(h.ctx), /scoped context required/)
})

test('agent-core: 在实际 Agent 创建后安装限制，保留从预设继承的 skill', () => {
  const h=harness(['unsafe_shell','skill','support_reference','recall_history'])
  let created, removed=false
  apply({effect:fn=>fn(),on:(event,fn)=>{assert.equal(event,'agent/created');created=fn;return()=>{removed=true}}})
  assert.equal(h.masks.size,0)
  created({agent:{ctx:h.ctx}})
  assert.deepEqual(h.visible(),['skill','support_reference','recall_history'])
  h.dispose();assert.equal(h.masks.size,0)
})

test('agent-core: 名称桥接供现有启动动画读取，卸载还原且不覆盖其他写入', () => {
  const previous = { unrelated: true, agentDisplayName: '旧名' }
  const root = { __CHENGMENG_CONFIG__: previous }
  const off = installPublicConfig(root, '澄梦')
  assert.equal(agentDisplayName(root), '澄梦')
  assert.equal(root.__CHENGMENG_CONFIG__.unrelated, true)
  off()
  assert.equal(root.__CHENGMENG_CONFIG__, previous)
  const off2 = installPublicConfig(root, '新名')
  root.__CHENGMENG_CONFIG__ = { agentDisplayName: '后来的配置' }
  off2()
  assert.equal(agentDisplayName(root), '后来的配置')
})

test('agent-core: 浏览器产物无需网络、DOM 或 React，注册可撤销的公开名称', async () => {
  const script = await readFile(new URL('lib/client.js', root), 'utf8')
  let record
  const sandbox = { window: { __ModuleLoader__: { load: item => { record = item } } } }
  runInNewContext(script, sandbox)
  const effects = []
  const exports = record.factory(() => { throw new Error('unexpected dependency') })
  assert.equal(exports.name, '@chengmeng/dsh-agent-core')
  assert.equal(exports.inject.length, 0)
  exports.apply({ effect: fn => effects.push(fn()) })
  assert.equal(sandbox.__CHENGMENG_CONFIG__.agentDisplayName, config.AGENT_DISPLAY_NAME)
  effects.forEach(off => off())
  assert.equal(sandbox.__CHENGMENG_CONFIG__, undefined)
  assert(!/fetch\(|XMLHttpRequest|localStorage|innerHTML|console\.log|Notification/.test(script))
})

