import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { resolve } from 'node:path'
import { validateAgentConfig } from '../src/config.js'
import { createPatch, toYaml, PACKAGE_NAME } from '../src/composition.js'

const root = fileURLToPath(new URL('..', import.meta.url))
const config = validateAgentConfig(JSON.parse(await readFile(resolve(root, 'config/agent.json'), 'utf8')))
const persona = await readFile(resolve(root, 'persona/persona.md'), 'utf8')
const replyStyle = await readFile(resolve(root, 'persona/reply-style.md'), 'utf8')
const patch = '# Generated by scripts/build.mjs; edit config/agent.json or persona/persona.md.\n'
  + toYaml(createPatch(config, persona, replyStyle)) + '\n'
const bridge = (await readFile(resolve(root, 'src/client-config.js'), 'utf8')).replace(/^export /gm, '')
// No runtime dependencies: this plugin can initialize before the UI renderer.
// Name configuration is available when startup-animation mounts its React view.
const bundle = `// Generated public display configuration. Contains no user data.\nwindow.__ModuleLoader__.load({\n  id: ${JSON.stringify(PACKAGE_NAME)},\n  factory: function (require) {\n${bridge}\n    return {\n      name: ${JSON.stringify(PACKAGE_NAME)},\n      inject: [],\n      apply: function (ctx) {\n        ctx.effect(function () { return installPublicConfig(globalThis, ${JSON.stringify(config.AGENT_DISPLAY_NAME)}); }, 'chengmeng-agent-core: public name');\n      }\n    };\n  }\n});\n`
if (process.argv.includes('--check')) {
  for (const [file, expected] of [['cordis.patch.yml', patch], ['lib/client.js', bundle]]) {
    if (await readFile(resolve(root, file), 'utf8') !== expected) throw new Error(`STALE_BUILD: ${file}`)
  }
  process.stdout.write('agent-core: build artifacts are current\n')
} else {
  await mkdir(resolve(root, 'lib'), { recursive: true })
  await writeFile(resolve(root, 'cordis.patch.yml'), patch, 'utf8')
  await writeFile(resolve(root, 'lib/client.js'), bundle, 'utf8')
  process.stdout.write('agent-core: built native preset and public name bridge\n')
}
